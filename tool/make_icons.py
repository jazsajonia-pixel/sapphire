"""Generate every Sapphire brand asset from one geometry.

The mark is a step-cut sapphire seen from above whose table is a note page
with a folded corner. The same points are used by `SapphireMarkPainter` in
lib/app/theme.dart, so the launcher icon, the splash and the in-app mark match.

Outputs:
  assets/branding/sapphire-mark.svg        vector source (transparent)
  docs/assets/sapphire-icon-512.png        store / README icon
  android/.../drawable/ic_sapphire_mark*.xml  adaptive foreground, monochrome, splash
  android/.../mipmap-*/ic_launcher.png     legacy launcher icons (API < 26)

Run: python3 tool/make_icons.py   (needs Pillow)
"""
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "android/app/src/main/res"

# Keep in sync with SapphireMarkPainter (lib/app/theme.dart).
OUTER = [(.33, .05), (.67, .05), (.83, .21), (.83, .79), (.67, .95), (.33, .95), (.17, .79), (.17, .21)]
TABLE = [(.43, .27), (.53, .27), (.64, .38), (.64, .66), (.57, .73), (.43, .73), (.36, .66), (.36, .34)]
FOLD = [(.53, .27), (.53, .38), (.64, .38)]
FACETS = ["#5E95FF", "#2F6BF2", "#1E4FD0", "#163DA6", "#0F2D80", "#1A46BC", "#2F6BF2", "#8FB8FF"]
TABLE_COLOR = "#D6E4FF"
FOLD_COLOR = "#8FB8FF"
ICON_BG = "#0B1430"  # launcher background (deep sapphire night)
SPLASH_BG = "#05080F"  # SapphireTheme.ink

DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}


def shapes():
    """(points, color) in paint order, unit coordinates."""
    out = []
    for i in range(8):
        j = (i + 1) % 8
        out.append(([OUTER[i], OUTER[j], TABLE[j], TABLE[i]], FACETS[i]))
    out.append((TABLE, TABLE_COLOR))
    out.append((FOLD, FOLD_COLOR))
    return out


def vector_path(pts, scale, ox, oy):
    cmds = [f"{'M' if k == 0 else 'L'}{ox + x * scale:.2f},{oy + y * scale:.2f}" for k, (x, y) in enumerate(pts)]
    return " ".join(cmds) + " Z"


def android_vector(scale, ox, oy, monochrome=False):
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tool/make_icons.py. Do not edit by hand. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp" android:height="108dp"',
        '    android:viewportWidth="108" android:viewportHeight="108">',
    ]
    if monochrome:
        # Silhouette with the page (table) cut out; the fold stays solid.
        d = vector_path(OUTER, scale, ox, oy) + " " + vector_path(TABLE, scale, ox, oy)
        lines.append(f'    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="{d}" />')
        lines.append(f'    <path android:fillColor="#FFFFFFFF" android:pathData="{vector_path(FOLD, scale, ox, oy)}" />')
    else:
        for pts, color in shapes():
            lines.append(f'    <path android:fillColor="{color}" android:pathData="{vector_path(pts, scale, ox, oy)}" />')
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def svg(size=1024):
    body = "\n".join(
        f'  <path fill="{c}" d="{vector_path(p, size, 0, 0)}"/>' for p, c in shapes()
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" width="{size}" height="{size}">\n'
        "  <title>Sapphire</title>\n"
        f"{body}\n</svg>\n"
    )


def render(px, mark_fraction, background, radius_fraction=0.0):
    """Raster icon: background (optionally rounded) + centered mark, 4x supersampled."""
    ss = 4
    big = px * ss
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if background:
        if radius_fraction:
            d.rounded_rectangle([0, 0, big - 1, big - 1], radius=round(big * radius_fraction), fill=background)
        else:
            d.rectangle([0, 0, big, big], fill=background)
    scale = big * mark_fraction
    off = (big - scale) / 2
    for pts, color in shapes():
        d.polygon([(off + x * scale, off + y * scale) for x, y in pts], fill=color)
    return img.resize((px, px), Image.Resampling.LANCZOS)


def main():
    drawable = RES / "drawable"
    # Adaptive foreground: mark inside the 66dp safe zone of the 108dp canvas.
    safe, off = 60.0, 24.0
    (drawable / "ic_sapphire_mark_foreground.xml").write_text(android_vector(safe, off, off), encoding="utf-8")
    (drawable / "ic_sapphire_mark_monochrome.xml").write_text(
        android_vector(safe, off, off, monochrome=True), encoding="utf-8"
    )
    # Splash (pre-Flutter window background): same size as the Flutter loader mark.
    (drawable / "ic_sapphire_mark.xml").write_text(android_vector(44.0, 32.0, 32.0), encoding="utf-8")
    # Old raster foregrounds are replaced by the vectors above.
    for density in DENSITIES:
        for name in ("ic_sapphire_mark_foreground.png", "ic_sapphire_mark_monochrome.png"):
            old = RES / f"drawable-{density}" / name
            if old.exists():
                old.unlink()
        folder = RES / f"drawable-{density}"
        if folder.exists() and not any(folder.iterdir()):
            folder.rmdir()

    (RES / "mipmap-anydpi-v26/ic_launcher.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/sapphire_icon_background" />\n'
        '    <foreground android:drawable="@drawable/ic_sapphire_mark_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_sapphire_mark_monochrome" />\n'
        "</adaptive-icon>\n",
        encoding="utf-8",
    )
    (RES / "values/colors.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="sapphire_splash_surface">{SPLASH_BG}</color>\n'
        f'    <color name="sapphire_icon_background">{ICON_BG}</color>\n'
        "</resources>\n",
        encoding="utf-8",
    )

    for density, factor in DENSITIES.items():
        folder = RES / f"mipmap-{density}"
        folder.mkdir(parents=True, exist_ok=True)
        render(round(48 * factor), 0.70, ICON_BG, 0.22).save(folder / "ic_launcher.png")

    branding = ROOT / "assets/branding"
    branding.mkdir(parents=True, exist_ok=True)
    (branding / "sapphire-mark.svg").write_text(svg(), encoding="utf-8")
    old_png = branding / "sapphire-mark.png"
    if old_png.exists():
        old_png.unlink()
    render(1024, 1.0, None).save(branding / "sapphire-mark-1024.png")
    (ROOT / "docs/assets").mkdir(parents=True, exist_ok=True)
    render(512, 0.62, ICON_BG, 0.22).save(ROOT / "docs/assets/sapphire-icon-512.png")


if __name__ == "__main__":
    main()
